// Package alerting tells an operator about the things nobody is watching for:
// an upstream account about to run dry, one that stopped working, a key or
// end user about to hit its spending limit, a long allowance about to reset
// with most of it unused.
//
// The unit is the tenant. Everything the rules look at (accounts, keys, end
// users, their usage) belongs to one tenant, so each tenant carries its own
// channels and thresholds and is only ever told about its own things. Accounts
// the platform shares with tenants belong to the system tenant, which is
// therefore the one that hears about them.
//
// Alerting is off until a tenant switches it on and gives it a channel, and it
// is never on the request path: rules are evaluated by one background loop from
// data that is already stored, and delivery runs on its own workers with a hard
// timeout. A channel that is down costs a log line.
package alerting

import (
	"fmt"
	"net/url"
	"strings"
	"time"

	"github.com/google/uuid"
)

// Keys of the runtime_settings rows (one per tenant) alerting keeps.
const (
	// SettingKey holds Settings: channels and thresholds an operator edits.
	SettingKey = "alerts"
	// EventsKey holds the bounded history of what was sent.
	EventsKey = "alerts-events"
	// SentKey holds which alerts were already sent and until when they stay
	// quiet. It is kept apart from the history so that a test message written
	// by a management request never races the evaluation loop's bookkeeping.
	SentKey = "alerts-sent"
)

// Channel kinds.
const (
	KindWebhook  = "webhook"
	KindFeishu   = "feishu"
	KindTelegram = "telegram"
)

// Rule names, as they appear in events and in webhook payloads.
const (
	RuleQuotaWindow    = "quota_window"
	RuleAccountFailure = "account_failure"
	RuleSpending       = "spending"
	RuleUseItOrLoseIt  = "use_it_or_lose_it"
	// RuleTest marks the message an operator sent to try a channel.
	RuleTest = "test"
)

// Languages the message text is written in. Webhook payloads also carry the
// structured fields, so a receiver that wants its own wording has them.
const (
	LanguageEN   = "en"
	LanguageZHCN = "zh-CN"
)

// Limits and defaults. The defaults are what a tenant gets by switching
// alerting on without touching a threshold; the reasoning is in the comments.
const (
	// MaxChannels bounds the settings row and what one evaluation round fans
	// out to.
	MaxChannels = 8

	maxNameLength   = 64
	maxSecretLength = 512

	// DefaultCooldownMinutes keeps one problem from being repeated more than
	// four times a day. Rules tied to a period (a quota window, a spending
	// window) are quiet for the rest of that period regardless; the cooldown is
	// what bounds the ones that are not, and the period rules when the upstream
	// does not say when a window ends.
	DefaultCooldownMinutes = 360
	MinCooldownMinutes     = 10
	MaxCooldownMinutes     = 7 * 24 * 60

	// DefaultUsageThresholdPercent matches the 90% mark at which the reset-aware
	// scheduler starts steering traffic away from an account: past it the
	// account is already being treated as nearly gone, and 99% is too late to
	// do anything about it.
	DefaultUsageThresholdPercent = 90

	// DefaultFailureMinutes waits out the failures that heal themselves. An
	// upstream timeout or 5xx usually clears within minutes; a revoked
	// credential does not, and is reported at once regardless (see Failure.Immediate).
	DefaultFailureMinutes = 10
	MaxFailureMinutes     = 24 * 60

	// DefaultMinRemainingPercent and DefaultHoursBeforeReset: a weekly allowance
	// with 40% unused that resets within a day is real waste, while the same
	// reminder three days out is only noise.
	DefaultMinRemainingPercent = 40
	DefaultHoursBeforeReset    = 24
	MaxHoursBeforeReset        = 7 * 24
)

// Settings is the stored form of one tenant's alerting configuration. The
// secrets in its channels are stored as they are (like every other credential
// in the settings store) and are never returned by the management API: see
// View.
type Settings struct {
	// Enabled is the master switch. Off by default; with it off nothing is
	// evaluated and nothing is sent, whatever the channels say.
	Enabled         bool      `json:"enabled"`
	Language        string    `json:"language"`
	CooldownMinutes int       `json:"cooldown_minutes"`
	Channels        []Channel `json:"channels"`
	Rules           Rules     `json:"rules"`
	UpdatedAt       time.Time `json:"updated_at,omitzero"`
}

// Channel is one place alerts are delivered to.
type Channel struct {
	// ID is generated by the server. It is what lets an edit that echoes a
	// masked secret back keep the secret it stands for.
	ID      string `json:"id"`
	Kind    string `json:"kind"`
	Name    string `json:"name"`
	Enabled bool   `json:"enabled"`

	// URL is the webhook address (webhook, feishu). Chat webhook addresses carry
	// their credential in the path, so it is a secret like the rest.
	URL string `json:"url,omitempty"`
	// Secret signs the request: an HMAC key for a generic webhook, the
	// "signature verification" key of a Feishu custom bot. Optional.
	Secret string `json:"secret,omitempty"`

	// BotToken and ChatID address a Telegram chat.
	BotToken string `json:"bot_token,omitempty"`
	ChatID   string `json:"chat_id,omitempty"`
}

// Rules holds the thresholds of every rule.
type Rules struct {
	QuotaWindow    QuotaWindowRule    `json:"quota_window"`
	AccountFailure AccountFailureRule `json:"account_failure"`
	Spending       SpendingRule       `json:"spending"`
	UseItOrLoseIt  UseItOrLoseItRule  `json:"use_it_or_lose_it"`
}

// QuotaWindowRule fires when an upstream account has used ThresholdPercent of
// one of its quota windows.
type QuotaWindowRule struct {
	Enabled          bool `json:"enabled"`
	ThresholdPercent int  `json:"threshold_percent"`
}

// AccountFailureRule fires when an upstream account that the operator did not
// switch off has been refused or failing for ForMinutes.
type AccountFailureRule struct {
	Enabled    bool `json:"enabled"`
	ForMinutes int  `json:"for_minutes"`
}

// SpendingRule fires when a key or an end user has used ThresholdPercent of one
// of its limits.
type SpendingRule struct {
	Enabled          bool `json:"enabled"`
	ThresholdPercent int  `json:"threshold_percent"`
}

// UseItOrLoseItRule fires when a window of a week or longer still has
// MinRemainingPercent left and resets within HoursBeforeReset.
type UseItOrLoseItRule struct {
	Enabled             bool `json:"enabled"`
	MinRemainingPercent int  `json:"min_remaining_percent"`
	HoursBeforeReset    int  `json:"hours_before_reset"`
}

// DefaultRules is what a tenant that never saved the rules gets. The last rule
// is a reminder rather than a problem, so it starts off.
func DefaultRules() Rules {
	return Rules{
		QuotaWindow:    QuotaWindowRule{Enabled: true, ThresholdPercent: DefaultUsageThresholdPercent},
		AccountFailure: AccountFailureRule{Enabled: true, ForMinutes: DefaultFailureMinutes},
		Spending:       SpendingRule{Enabled: true, ThresholdPercent: DefaultUsageThresholdPercent},
		UseItOrLoseIt: UseItOrLoseItRule{
			Enabled:             false,
			MinRemainingPercent: DefaultMinRemainingPercent,
			HoursBeforeReset:    DefaultHoursBeforeReset,
		},
	}
}

// DefaultSettings is the configuration of a tenant that never saved one:
// everything off, nothing to deliver to.
func DefaultSettings() Settings {
	return Settings{
		Language:        LanguageEN,
		CooldownMinutes: DefaultCooldownMinutes,
		Channels:        []Channel{},
		Rules:           DefaultRules(),
	}
}

// Normalized repairs what a stored row may lack or hold out of range, for the
// read side: the evaluation loop must keep working on a row written by an
// older build or edited by hand, where a write path would refuse it (see
// Validate).
func (s Settings) Normalized() Settings {
	if s.Rules == (Rules{}) {
		s.Rules = DefaultRules()
	}
	s.Language = normalizeLanguage(s.Language)
	s.CooldownMinutes = clamp(s.CooldownMinutes, MinCooldownMinutes, MaxCooldownMinutes, DefaultCooldownMinutes)
	s.Rules.QuotaWindow.ThresholdPercent = clamp(s.Rules.QuotaWindow.ThresholdPercent, 1, 100, DefaultUsageThresholdPercent)
	s.Rules.Spending.ThresholdPercent = clamp(s.Rules.Spending.ThresholdPercent, 1, 100, DefaultUsageThresholdPercent)
	s.Rules.AccountFailure.ForMinutes = clamp(s.Rules.AccountFailure.ForMinutes, 0, MaxFailureMinutes, DefaultFailureMinutes)
	s.Rules.UseItOrLoseIt.MinRemainingPercent = clamp(s.Rules.UseItOrLoseIt.MinRemainingPercent, 1, 100, DefaultMinRemainingPercent)
	s.Rules.UseItOrLoseIt.HoursBeforeReset = clamp(s.Rules.UseItOrLoseIt.HoursBeforeReset, 1, MaxHoursBeforeReset, DefaultHoursBeforeReset)
	channels := make([]Channel, 0, len(s.Channels))
	for _, channel := range s.Channels {
		if len(channels) >= MaxChannels {
			break
		}
		channels = append(channels, channel.normalized())
	}
	s.Channels = channels
	return s
}

func (c Channel) normalized() Channel {
	c.ID = strings.TrimSpace(c.ID)
	c.Kind = strings.ToLower(strings.TrimSpace(c.Kind))
	c.Name = strings.TrimSpace(c.Name)
	c.URL = strings.TrimSpace(c.URL)
	c.Secret = strings.TrimSpace(c.Secret)
	c.BotToken = strings.TrimSpace(c.BotToken)
	c.ChatID = strings.TrimSpace(c.ChatID)
	return c
}

// ActiveChannels returns the channels an alert would be delivered to.
func (s Settings) ActiveChannels() []Channel {
	out := make([]Channel, 0, len(s.Channels))
	for _, channel := range s.Channels {
		if channel.Enabled && channel.deliverable() {
			out = append(out, channel)
		}
	}
	return out
}

// Active reports whether this tenant should be evaluated at all: switched on
// and with somewhere to send to. A tenant that is neither costs one settings
// read per round and nothing else.
func (s Settings) Active() bool {
	return s.Enabled && len(s.ActiveChannels()) > 0
}

// RulesEnabled reports whether any rule is on.
func (s Settings) RulesEnabled() bool {
	r := s.Rules
	return r.QuotaWindow.Enabled || r.AccountFailure.Enabled || r.Spending.Enabled || r.UseItOrLoseIt.Enabled
}

// deliverable reports whether the channel holds what its kind needs to send.
func (c Channel) deliverable() bool {
	switch c.Kind {
	case KindWebhook, KindFeishu:
		return c.URL != ""
	case KindTelegram:
		return c.BotToken != "" && c.ChatID != ""
	default:
		return false
	}
}

func normalizeLanguage(language string) string {
	switch strings.TrimSpace(language) {
	case LanguageZHCN, "zh", "zh-cn", "zh_CN":
		return LanguageZHCN
	default:
		return LanguageEN
	}
}

// clamp returns fallback for a value that was never set (zero) outside the
// range and the nearest bound for one that was, so a hand-edited 5000% still
// alerts instead of silently disabling the rule.
func clamp(value, lo, hi, fallback int) int {
	if value == 0 && lo > 0 {
		return fallback
	}
	return min(max(value, lo), hi)
}

// FieldError is a rejected setting, with the field to point the operator at.
type FieldError struct {
	Field   string
	Message string
}

func (e *FieldError) Error() string {
	if e == nil {
		return ""
	}
	return fmt.Sprintf("%s: %s", e.Field, e.Message)
}

func fieldErr(field, format string, args ...any) *FieldError {
	return &FieldError{Field: field, Message: fmt.Sprintf(format, args...)}
}

// Validate checks what a management write is about to store. allowPrivate says
// whether a generic webhook may point at a private address: only the platform's
// own tenant is trusted with that, because the server makes the request from
// inside its own network (see ValidateWebhookURL).
func (s Settings) Validate(allowPrivate bool) *FieldError {
	if s.Language != LanguageEN && s.Language != LanguageZHCN {
		return fieldErr("language", "must be %q or %q", LanguageEN, LanguageZHCN)
	}
	if s.CooldownMinutes < MinCooldownMinutes || s.CooldownMinutes > MaxCooldownMinutes {
		return fieldErr("cooldown_minutes", "must be between %d and %d", MinCooldownMinutes, MaxCooldownMinutes)
	}
	if len(s.Channels) > MaxChannels {
		return fieldErr("channels", "at most %d channels", MaxChannels)
	}
	seen := make(map[string]struct{}, len(s.Channels))
	for i, channel := range s.Channels {
		field := fmt.Sprintf("channels[%d]", i)
		if _, dup := seen[channel.ID]; dup {
			return fieldErr(field+".id", "duplicate channel id")
		}
		seen[channel.ID] = struct{}{}
		if err := channel.validate(field, allowPrivate); err != nil {
			return err
		}
	}
	r := s.Rules
	if err := inRange("rules.quota_window.threshold_percent", r.QuotaWindow.ThresholdPercent, 1, 100); err != nil {
		return err
	}
	if err := inRange("rules.account_failure.for_minutes", r.AccountFailure.ForMinutes, 0, MaxFailureMinutes); err != nil {
		return err
	}
	if err := inRange("rules.spending.threshold_percent", r.Spending.ThresholdPercent, 1, 100); err != nil {
		return err
	}
	if err := inRange("rules.use_it_or_lose_it.min_remaining_percent", r.UseItOrLoseIt.MinRemainingPercent, 1, 100); err != nil {
		return err
	}
	return inRange("rules.use_it_or_lose_it.hours_before_reset", r.UseItOrLoseIt.HoursBeforeReset, 1, MaxHoursBeforeReset)
}

func inRange(field string, value, lo, hi int) *FieldError {
	if value < lo || value > hi {
		return fieldErr(field, "must be between %d and %d", lo, hi)
	}
	return nil
}

// validate checks one channel. A channel that is switched off is still checked:
// a typo saved today would otherwise surface the day somebody switches it on.
func (c Channel) validate(field string, allowPrivate bool) *FieldError {
	if c.Name == "" {
		return fieldErr(field+".name", "is required")
	}
	if len(c.Name) > maxNameLength {
		return fieldErr(field+".name", "must be at most %d characters", maxNameLength)
	}
	if len(c.Secret) > maxSecretLength || len(c.URL) > maxSecretLength || len(c.BotToken) > maxSecretLength {
		return fieldErr(field, "a value is longer than %d characters", maxSecretLength)
	}
	switch c.Kind {
	case KindWebhook:
		if c.URL == "" {
			return fieldErr(field+".url", "is required")
		}
		if err := ValidateWebhookURL(c.URL, allowPrivate); err != nil {
			return fieldErr(field+".url", "%s", err.Error())
		}
	case KindFeishu:
		if c.URL == "" {
			return fieldErr(field+".url", "is required")
		}
		if err := ValidateFeishuURL(c.URL); err != nil {
			return fieldErr(field+".url", "%s", err.Error())
		}
	case KindTelegram:
		if err := ValidateTelegramToken(c.BotToken); err != nil {
			return fieldErr(field+".bot_token", "%s", err.Error())
		}
		if err := ValidateTelegramChatID(c.ChatID); err != nil {
			return fieldErr(field+".chat_id", "%s", err.Error())
		}
	default:
		return fieldErr(field+".kind", "must be %q, %q or %q", KindWebhook, KindFeishu, KindTelegram)
	}
	return nil
}

// newChannelID returns the id of a channel created by a write.
func newChannelID() string { return uuid.NewString() }

// hostOf is the part of a URL that is safe to show: scheme and host, never the
// path, where chat webhooks keep their credential.
func hostOf(raw string) string {
	parsed, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || parsed.Host == "" {
		return ""
	}
	return parsed.Scheme + "://" + parsed.Host
}
